    /// <summary>
    /// 获取节日祝福（返回标题 + 消息，用于 AddText(title).AddText(message)）
    /// </summary>
    public (string Title, string Message) GetGreeting(DateTime date)
    {
        string key = date.ToString("MM-dd");

        if (holidayMessages.TryGetValue(key, out var tuple))
        {
            return tuple;
        }

        return ("普通的一天", "今天不是节假日，但你完全可以假装放假，比如‘为了人类和平先休息一下’。");
    }
}